BEGIN;
CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE TABLE IF NOT EXISTS users(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 trial_started_at TEXT
);
CREATE TABLE IF NOT EXISTS sessions(
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expiration ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS accounts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL CHECK(char_length(name) BETWEEN 1 AND 100),
 balance_cents BIGINT NOT NULL DEFAULT 0,
 protected_cents BIGINT NOT NULL DEFAULT 0 CHECK(protected_cents >= 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_accounts_user ON accounts(user_id);
CREATE TABLE IF NOT EXISTS items(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL CHECK(char_length(name) BETWEEN 1 AND 100),
 kind TEXT NOT NULL CHECK(kind IN ('income','bill','subscription','debt','budget','goal')),
 amount_cents BIGINT NOT NULL CHECK(amount_cents >= 0),
 due_date TEXT NOT NULL CHECK(due_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
 frequency TEXT NOT NULL CHECK(frequency IN ('once','weekly','biweekly','monthly','yearly')),
 status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN ('planned','paid','canceled')),
 certainty TEXT NOT NULL DEFAULT 'confirmed' CHECK(certainty IN ('confirmed','estimated')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_items_user ON items(user_id,due_date);
INSERT INTO schema_migrations(version) VALUES(1) ON CONFLICT(version) DO NOTHING;
COMMIT;